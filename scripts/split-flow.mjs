// Repostar con un viaje en curso (demo, Javier): se termina en el km del repostaje y empieza otro.
import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('dialog', (d) => d.accept());
await p.goto('http://localhost:5173/?demo&como=javier#/repostajes/nuevo');
await p.waitForTimeout(900);
const files = await p.$$('input[type=file]');
await files[0].setInputFiles('public/icons/icon-192.png');
await p.waitForTimeout(1500);
await p.fill('#r-amount', '61,50');
await p.fill('#r-price', '1,549');
const odo = await p.$('#odo-km');
await odo.fill('182800');
await odo.dispatchEvent('input');
await p.waitForTimeout(500);
console.log('aviso:', await p.$eval('.split-note', (e) => e.innerText.replace(/\s+/g, ' ')).catch(() => 'NO SALE'));
console.log('reparto:', await p.$eval('.split-list', (e) => e.innerText.replace(/\s+/g, ' ')).catch(() => '-'));
await (await p.$('.split-note'))?.scrollIntoViewIfNeeded();
await p.screenshot({ path: '.impeccable/review/split-form.png' });
await p.click('form button[type=submit]');
await p.waitForTimeout(900);
console.log('error:', await p.$eval('form .error[role=alert]', (e) => e.textContent).catch(() => '-'));
console.log('aviso final:', await p.$eval('dialog[open]', (e) => e.innerText.replace(/\s+/g, ' ')).catch(() => 'NO SALE'));
await (await p.$('dialog[open]'))?.screenshot({ path: '.impeccable/review/split-dialog.png' });
await p.click('dialog[open] .btn.primary').catch(() => {});
await p.evaluate(() => (location.hash = '#/'));
await p.waitForTimeout(700);
console.log('resumen:', await p.$eval('main', (e) => (e.innerText.match(/Terminar viaje[^\n]*/) || ['sin botón'])[0]));
await p.evaluate(() => (location.hash = '#/viajes'));
await p.waitForTimeout(700);
console.log('viajes Javier:', await p.$$eval('.person-card', (cs) => cs.filter((c) => c.innerText.startsWith('Javier')).map((c) => c.innerText.replace(/\s+/g, ' ').slice(0, 220))));
// Marta: no tiene viaje en curso → no sale el aviso
await p.goto('http://localhost:5173/?demo&como=marta#/repostajes/nuevo');
await p.waitForTimeout(800);
const o2 = await p.$('#odo-km'); await o2.fill('182800'); await o2.dispatchEvent('input'); await p.waitForTimeout(400);
console.log('Marta aviso propio:', (await p.$('.split-note')) ? 'SALE (mal)' : 'no sale', '| aviso de otro:', await p.$eval('.warn-line', (e) => e.innerText).catch(() => '-'));
await b.close();
